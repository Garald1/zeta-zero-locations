"""Literal table of Bernoulli numbers B_0..B_{M-1} (Mathlib convention B_1 = -1/2) as (num, den).
Checked against Mathlib's `bernoulli` by the kernel (ZetaCert/BernTable.lean)."""
import sys
from fractions import Fraction
from math import comb
M = int(sys.argv[1]); out = sys.argv[2]
B = []
for j in range(M):
    s = sum(comb(j + 1, k) * B[k] for k in range(j))
    B.append((Fraction(1 if j == 0 else 0) - s) / (j + 1))
with open(out, "w") as f:
    f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
    f.write("import ZetaCert.Bernoulli\nimport ZetaCert.Eval.EMRestSound\n\n")
    f.write(f"/-! Bernoulli numbers `B_0, …, B_{M-1}` (generated by scripts/gen_bern.py), checked against Mathlib. -/\n\n")
    f.write("namespace ZetaCert.Data\n\nopen ZetaCert ZetaCert.Eval\n\n")
    f.write(f"/-- `(num, den)` of `B_j`, `j < {M}`. -/\ndef bern : List (Int × Nat) := [\n")
    f.write(",\n".join(f"  ({b.numerator}, {b.denominator})" for b in B))
    f.write("]\n\n")
    f.write(f"/-- Table size. -/\ndef bernM : Nat := {M}\n\n")
    f.write(f"theorem bern_eq : bern = (bernList {M}).map (fun q => (q.num, q.den)) := by decide +kernel\n\n")
    f.write(f"""theorem bern_ok : BernOK bern {M - 1} := by
  intro j hj
  have hlen : j < (bernList {M}).length := by rw [bernList_length]; omega
  have hb := bernList_spec {M} j (by omega)
  have e : bernAt bern j = (((bernList {M}).getD j 0).num, ((bernList {M}).getD j 0).den) := by
    rw [bernAt, bern_eq, List.getD_eq_getElem?_getD, List.getElem?_map, List.getD_eq_getElem?_getD,
      List.getElem?_eq_getElem hlen, Option.map_some, Option.getD_some, Option.getD_some]
  rw [e, hb]
  exact ⟨Rat.den_pos _, by push_cast; exact (Rat.num_div_den _).symm⟩

end ZetaCert.Data
""")

