"""Root data for the evaluator at general real part: x_p = floor(2^128 p^(-1/q)), q = 4096, with
x^q p <= 2^(128 q) < (x+1)^q p (checked by the kernel, ZetaCert/RootDataCheck.lean)."""
import sys
from mpmath import mp, mpf, power
sys.path.insert(0, 'scripts')
from gen_primedata import primes_upto
mp.dps = 80
Q = 4096
PMAX = int(sys.argv[1]); out = sys.argv[2]
ents = []
for p in primes_upto(PMAX):
    x = int(mp.floor(mpf(2)**128 * power(p, -mpf(1)/Q)))
    B = 2**(128*Q)
    while x**Q * p > B: x -= 1
    while (x+1)**Q * p <= B: x += 1
    ents.append((p, x))
with open(out, "w") as f:
    f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
    f.write(f"/-! `(p, x)` with `x ≈ 2^128 p^(-1/{Q})` for the primes `p ≤ {PMAX}` (generated by scripts/gen_rootdata.py). -/\n\nnamespace ZetaCert.Data\n\n")
    chunks = [ents[i:i+150] for i in range(0, len(ents), 150)]
    for ci, ch in enumerate(chunks):
        f.write(f"def rc{ci} : List (Nat × Nat) := [\n" + ",\n".join(f"  ({p}, {x})" for p, x in ch) + "]\n\n")
    f.write("def rcAll : List (Nat × Nat) := " + " ++ ".join(f"rc{i}" for i in range(len(chunks))) + "\n\nend ZetaCert.Data\n")
print(len(ents))
