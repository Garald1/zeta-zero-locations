"""Generate the per-zero certificate modules ZetaCert/Zeros<T>/Z<j>.lean (50 zeros each).

Each theorem `z_<i>` states, for the i-th listed ordinate m_i of the challenge file,
  ∃ t : ℝ, |t - m_i / 10^24| ≤ 1/10^20 ∧ riemannZeta (1/2 + t I) = 0,
and is proved by `zc_spec` with a `decide +kernel` certificate. The parameters (centre G, cut-off N,
EM order k, halvings K) are candidate data computed here; the kernel re-checks everything.

Usage: python3 scripts/gen_zero_modules.py 1000|10000 [extra-data-file]
"""
import sys, re, os
from mpmath import mp, mpf
sys.path.insert(0, 'scripts')
from zeroparams import params

mp.dps = 60
T = int(sys.argv[1])
chal = open(f'challenge/Challenge{T}.lean').read()
body = chal[chal.index(f'def ord{T}_0'):chal.index(f'def ordinates{T}')]
ms = [int(x) for x in re.findall(r'(\d{20,})', body)]
fn = 'data/zeros_T1000.txt' if T == 1000 else 'data/zeros_T10000.txt'
gs = [l.split()[1] for l in open(fn) if not l.startswith('#')]
extra = []
if len(sys.argv) > 2:
    extra = [l.split()[1] for l in open(sys.argv[2]) if not l.startswith('#')]
assert len(ms) == len(gs), (len(ms), len(gs))
for m, g in zip(ms, gs):
    assert int(mp.nint(mpf(g) * 10**24)) == m
outdir = f'ZetaCert/Zeros{T}'
os.makedirs(outdir, exist_ok=True)
entries = list(zip(ms, gs))
for g in extra:  # zeros above T used by the count (#10143 for T = 10^4)
    entries.append((int(mp.nint(mpf(g) * 10**24)), g))
per = 50
nmods = (len(entries) + per - 1) // per
for j in range(nmods):
    chunk = entries[j*per:(j+1)*per]
    with open(f'{outdir}/Z{j}.lean', 'w') as f:
        f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
        f.write("import ZetaCert.CertSound\n\n")
        f.write(f"/-! Zeros {j*per+1}–{j*per+len(chunk)} (generated by scripts/gen_zero_modules.py). -/\n\n")
        f.write(f"namespace ZetaCert.Zeros{T}\n\nopen ZetaCert Complex\n\n")
        for i, (m, g) in enumerate(chunk):
            idx = j*per + i + 1
            p = params(g, m)
            f.write(f"theorem z_{idx} : ∃ t : ℝ, |t - (({m} : ℕ) : ℝ) / 10 ^ 24| ≤ 1 / 10 ^ 20 ∧\n"
                    f"    riemannZeta (1 / 2 + t * I) = 0 :=\n"
                    f"  zc_spec (G := {p['G']}) (N := {p['N']}) (K := {p['K']}) (k := {p['k']}) "
                    f"(fuel := {p['fuel']}) (Dp := {p['Dp']}) (by decide +kernel)\n\n")
        f.write(f"end ZetaCert.Zeros{T}\n")
print(nmods, "modules,", len(entries), "zeros")
