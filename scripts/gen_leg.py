"""Generate the horizontal-leg modules: Re ζ(σ + i T2) > 0 for σ ∈ [1/2, 2].

Sample centres σ_i = j_i/4096 with half-widths h_i = H_i/4096; each is certified by `lc` and
`seg_of_lc`. The values v_i, d_i come from mpmath (candidate data; the kernel re-checks them).
Usage: python3 scripts/gen_leg.py <num> <den> <name> <m>   (T2 = num/den, den a power of 2)
"""
import sys, math, os
from fractions import Fraction as Fr
from mpmath import mp, mpf, mpc, zeta
sys.path.insert(0, 'scripts')
from zeroparams import choose

mp.dps = 30
num, den, name, m = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3], int(sys.argv[4])
T2 = Fr(num, den)
assert (2**80) % den == 0
G = num * (2**80 // den)
N, k = choose(mpf(num) / den)
K = max(0, math.ceil(math.log2(8 * float(T2) * math.log(N)))) + 1
Dp = N.bit_length()
T = T2
M2 = 2 * (Fr(m)**4 + Fr(m)**3 / (T - 2) + Fr(1, 2 * m) + (1 + 4 * (T + Fr(1, 4))) / m) / Fr(3, 16)**2


def vd(j):
    s = mpc(mpf(j) / 4096, mpf(num) / den)
    z = zeta(s); zp = zeta(s, derivative=1)
    v = Fr(math.floor((float(z.real) - 0.002) * 10**6), 10**6)
    d = Fr(math.ceil((abs(float(zp.real)) + abs(float(zp.imag)) + 0.002) * 10**6), 10**6)
    return v, d


def maxH(v, d):
    H = 256  # h ≤ 1/16
    while H > 0:
        h = Fr(H, 4096)
        if h * d + h * h * M2 < v * Fr(9, 10):
            return H
        H -= 1
    raise ValueError("no width")


pts = []
j = 2048
v, d = vd(j); H = maxH(v, d)
pts.append((j, H, v, d))
while j + H < 8192:
    jn = min(8192, j + 2 * H)
    while True:
        vn, dn = vd(jn); Hn = maxH(vn, dn)
        if jn - Hn <= j + H: break
        jn = (jn + j) // 2 + 1
    j, H, v, d = jn, Hn, vn, dn
    pts.append((j, H, v, d))
print(len(pts), "points; N", N, "k", k, "K", K)

outdir = f'ZetaCert/{name}'
os.makedirs(outdir, exist_ok=True)
per = 40
chunks = [pts[i:i + per] for i in range(0, len(pts), per)]
P = f"fun σ : ℝ => 0 < (riemannZeta (σ + (({G} : ℕ) / 2 ^ 80 : ℝ) * I)).re"
for ci, ch in enumerate(chunks):
    with open(f'{outdir}/L{ci}.lean', 'w') as f:
        f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
        f.write("import ZetaCert.Leg\n\n")
        f.write(f"/-! Leg at height {num}/{den}, points {ci*per}–{ci*per+len(ch)-1} (generated by scripts/gen_leg.py). -/\n\n")
        f.write(f"namespace ZetaCert.{name}\n\nopen ZetaCert Complex Set\n\n")
        for i, (j, H, v, d) in enumerate(ch):
            f.write(f"theorem p_{ci}_{i} : ∀ σ ∈ Icc (({j} : ℕ) / 4096 - ({H} : ℝ) / 4096) (({j} : ℕ) / 4096 + ({H} : ℝ) / 4096),\n"
                    f"    ({P}) σ :=\n"
                    f"  seg_of_lc (j := {j}) (G := {G}) (N := {N}) (K := {K}) (k := {k}) (fuel := 1000) (Dp := {Dp}) (m := {m})\n"
                    f"    (v := {v.numerator}/{v.denominator}) (d := {d.numerator}/{d.denominator}) (h := ({H} : ℝ) / 4096)\n"
                    f"    (by decide +kernel) (by norm_num) (by norm_num) (by norm_num) (by positivity) (by norm_num)\n"
                    f"    (by unfold M2; norm_num)\n\n")
        chain = f"p_{ci}_0"
        for i in range(1, len(ch)):
            chain = f"cover2 ({chain}) p_{ci}_{i} (by norm_num)"
        j0, H0 = ch[0][0], ch[0][1]; j1, H1 = ch[-1][0], ch[-1][1]
        f.write(f"theorem part_{ci} : ∀ σ ∈ Icc (({j0} : ℕ) / 4096 - ({H0} : ℝ) / 4096) (({j1} : ℕ) / 4096 + ({H1} : ℝ) / 4096),\n"
                f"    ({P}) σ :=\n  {chain}\n\nend ZetaCert.{name}\n")
with open(f'ZetaCert/{name}.lean', 'w') as f:
    f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
    for ci in range(len(chunks)):
        f.write(f"import ZetaCert.{name}.L{ci}\n")
    f.write(f"\n/-! `Re ζ(σ + iT₂) > 0` on `[1/2, 2]`, `T₂ = {num}/{den}`. -/\n\nnamespace ZetaCert.{name}\n\nopen ZetaCert Complex Set\n\n")
    chain = "part_0"
    for ci in range(1, len(chunks)):
        chain = f"cover2 ({chain}) part_{ci} (by norm_num)"
    j0, H0 = chunks[0][0][0], chunks[0][0][1]; j1, H1 = chunks[-1][-1][0], chunks[-1][-1][1]
    f.write(f"theorem leg_all : ∀ σ ∈ Icc (({j0} : ℕ) / 4096 - ({H0} : ℝ) / 4096) (({j1} : ℕ) / 4096 + ({H1} : ℝ) / 4096),\n"
            f"    ({P}) σ :=\n  {chain}\n\n")
    f.write(f"theorem leg : ∀ σ ∈ Icc (1 / 2 : ℝ) 2, 0 < (riemannZeta (σ + ((({num} : ℝ) / {den} : ℝ) : ℂ) * I)).re := by\n"
            f"  intro σ hσ\n"
            f"  have h := leg_all σ ⟨by norm_num at hσ ⊢; linarith [hσ.1], by norm_num at hσ ⊢; linarith [hσ.2]⟩\n"
            f"  have e : ((({G} : ℕ) : ℝ) / 2 ^ 80 : ℝ) = ({num} : ℝ) / {den} := by norm_num\n"
            f"  simp only at h; rw [e] at h; exact h\n\nend ZetaCert.{name}\n")
