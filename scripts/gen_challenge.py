"""Generate the challenge statements and comparator configurations from the Arb data.

Palomar (palomar-registry.org) accepts one Comparator configuration per submission, and a
challenge file may not exceed 100 KiB or 1,000 lines (warning above 32 KiB or 300 lines).
The 10 142 ordinates up to 10^4 do not fit in one file, so the statements are split:

* `Zeros{a}to{b}` for (a, b] = (0, 1000], (1000, 2000], ..., (9000, 10000]: every zero with
  a < Im s <= b is simple, on the critical line, and within 10^-20 of a listed ordinate; each
  listed interval holds exactly one zero; the number of such zeros.
* `Count10000`: every zero with 0 < Im s <= 10^4 is simple and on the line; there are 10 142.

Each ordinate gamma_k (40 significant digits, Arb radius <= 1.2e-44) is stored as the integer
m_k = round(10^24 * gamma_k).
"""
from decimal import Decimal, getcontext, ROUND_HALF_EVEN
import glob, json, os
getcontext().prec = 100
SCALE, CHUNK, PER_LINE = 24, 300, 6
HARD_BYTES, HARD_LINES, WARN_BYTES, WARN_LINES = 100 * 1024, 1000, 32 * 1024, 300

def load(path):
    rows = []
    for line in open(path):
        if line.startswith('#'):
            continue
        k, g, r = line.split()
        assert len(g.split('.')[1]) >= 30, g          # enough digits to round to 24 decimals
        assert float(r) < 1e-40
        rows.append((int(k), g))
    assert [k for k, _ in rows] == list(range(1, len(rows) + 1))
    return rows

def scaled(g):
    d = Decimal(g) * (Decimal(10) ** SCALE)
    m = int(d.to_integral_value(rounding=ROUND_HALF_EVEN))
    assert abs(abs(d - m) - Decimal('0.5')) > Decimal('1e-10')  # rounding is unambiguous
    return m

HEADER = '''/-
DRAFT. Written in a sandbox without Mathlib: this file has NOT been elaborated yet.
Make it elaborate against the pinned Mathlib, changing syntax only. Never weaken it.
Generated by scripts/gen_challenge.py.
{body}
-/
import Mathlib

namespace {ns}

/-- The zeros of `riemannZeta` with `a < Im s ≤ b` (no condition on `Re s`). -/
def zerosBetween (a b : ℝ) : Set ℂ := {{s | riemannZeta s = 0 ∧ a < s.im ∧ s.im ≤ b}}
'''

RANGE_BODY = '''
Trusted statement (for leanprover/comparator and Palomar): the location, to within 10^-20, of
every zero of Mathlib's `riemannZeta` with {a} < Im s <= {b}.

Data: `ordinates` lists, in increasing order, the integers m_k nearest to 10^24 * gamma_k, where
gamma_k = Im rho_k for the {n} zeros with {a} < Im rho <= {b} (zeros number {k0} to {k1}), as
computed by Arb (acb_dirichlet_zeta_zeros, 160-bit ball arithmetic, radius <= 1.2e-44 on each
gamma_k). The list is part of the statement; the proof must not assume it is correct.'''

RANGE_FOOTER = '''
/-- `ordinates` = `{parts}` ({n} entries). -/
def ordinates : List ℕ := {parts}

/-- Every zero of `ζ` with `{a} < Im s ≤ {b}` is simple, lies on the critical line, and has its
ordinate within `10⁻²⁰` of `m / 10²⁴` for some `m` in the list. -/
theorem located :
    ∀ s ∈ zerosBetween {a} {b}, s.re = 1 / 2 ∧ analyticOrderAt riemannZeta s = 1 ∧
      ∃ m ∈ ordinates, |s.im - (m : ℝ) / 10 ^ 24| ≤ 1 / 10 ^ 20 := by
  sorry

/-- For each listed `m`, exactly one zero of `ζ` has its ordinate within `10⁻²⁰` of `m / 10²⁴`. -/
theorem unique :
    ∀ m ∈ ordinates, ∃! s : ℂ, riemannZeta s = 0 ∧ |s.im - (m : ℝ) / 10 ^ 24| ≤ 1 / 10 ^ 20 := by
  sorry

/-- There are exactly {n} zeros of `ζ` with `{a} < Im s ≤ {b}`. -/
theorem count : (zerosBetween {a} {b}).ncard = {n} := by
  sorry

end {ns}
'''

COUNT_BODY = '''
Trusted statement (for leanprover/comparator and Palomar): every zero of Mathlib's
`riemannZeta` with 0 < Im s <= 10000 is simple and lies on the critical line, and there are
exactly 10142 of them. The ten files Zeros{a}to{b}.lean locate each of them to within 10^-20.'''

COUNT_FOOTER = '''
/-- Every zero of `ζ` with `0 < Im s ≤ 10000` is simple and lies on the critical line. -/
theorem on_line_and_simple :
    ∀ s ∈ zerosBetween 0 10000, s.re = 1 / 2 ∧ analyticOrderAt riemannZeta s = 1 := by
  sorry

/-- There are exactly 10142 zeros of `ζ` with `0 < Im s ≤ 10000`. -/
theorem count : (zerosBetween 0 10000).ncard = 10142 := by
  sorry

end Count10000
'''

def check_size(path):
    data = open(path, 'rb').read()
    size, lines = len(data), data.count(b'\n') + 1
    assert size <= HARD_BYTES and lines <= HARD_LINES, (path, size, lines)
    warn = " (Palomar warning: over 32 KiB or 300 lines)" if size > WARN_BYTES or lines > WARN_LINES else ""
    return f"{size / 1024:.1f} KiB, {lines} lines{warn}"

def config(ns, theorems):
    return {
        "challenge_module": ns,
        "solution_module": f"{ns}Solution",
        "theorem_names": [f"{ns}.{t}" for t in theorems],
        "definition_names": [],
        "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
        "enable_nanoda": True,
    }

def main():
    rows = load("data/zeros_T10000.txt")
    assert len(rows) == 10142
    os.makedirs("challenge", exist_ok=True)
    for old in glob.glob("challenge/*"):
        os.remove(old)
    for a in range(0, 10000, 1000):
        b = a + 1000
        sel = [(k, g) for k, g in rows if a < float(g) <= b]
        # no ordinate within 10^-6 of a range boundary
        assert all(abs(float(g) - x) > 1e-6 for _, g in sel for x in (a, b))
        ms = [scaled(g) for _, g in sel]
        assert ms == sorted(ms) and len(set(ms)) == len(ms)
        n, ns = len(ms), f"Zeros{a}to{b}"
        out = [HEADER.format(ns=ns, body=RANGE_BODY.format(a=a, b=b, n=n, k0=sel[0][0], k1=sel[-1][0]))]
        names = []
        for c in range(0, n, CHUNK):
            nm = f"ord{c // CHUNK}"
            names.append(nm)
            part = ms[c:c + CHUNK]
            lines = [", ".join(str(m) for m in part[i:i + PER_LINE]) for i in range(0, len(part), PER_LINE)]
            out.append(f"/-- entries {c + 1}..{min(c + CHUNK, n)} -/\ndef {nm} : List ℕ := [\n  "
                       + ",\n  ".join(lines) + "]\n")
        out.append(RANGE_FOOTER.format(a=a, b=b, n=n, ns=ns, parts=" ++ ".join(names)))
        path = f"challenge/{ns}.lean"
        open(path, "w").write("\n".join(out))
        json.dump(config(ns, ["located", "unique", "count"]), open(f"challenge/comparator-{ns}.json", "w"), indent=2)
        print(f"{ns}: zeros {sel[0][0]}..{sel[-1][0]} (n = {n}); {check_size(path)}")
    path = "challenge/Count10000.lean"
    open(path, "w").write(HEADER.format(ns="Count10000", body=COUNT_BODY) + COUNT_FOOTER)
    json.dump(config("Count10000", ["on_line_and_simple", "count"]), open("challenge/comparator-Count10000.json", "w"), indent=2)
    print(f"Count10000: {check_size(path)}")

main()
