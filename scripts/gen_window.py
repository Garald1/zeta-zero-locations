"""Generate, for the range (a, b] of challenge/Zeros<a>to<b>.lean, the window count module
ZetaCert/Windows/W<a>to<b>.lean (Ncount L U = n) and the solution solution/Zeros<a>to<b>Solution.lean.

The window (L, U] has L ≤ a and b ≤ U, positive legs at both ends (ZetaCert/Legs/<name>.lean,
from scripts/gen_bleg.py) and no zero in (L, a]; the zeros in (b, U] are certified too
(scripts/gen_zero_modules.py a b U). Candidate data (logarithms, numerics) from mpmath; the kernel
re-checks everything.
Usage: python3 scripts/gen_window.py <a> <b>
"""
import sys, re, math
from fractions import Fraction as Fr
from mpmath import mp, mpf, log, pi
sys.path.insert(0, 'scripts')
from gen_primedata import entry, L2

mp.dps = 60
# boundary legs: B -> (lower-end leg, upper-end leg), each (name, num, den)
LEGS = {
    0: (('B3', 3, 1), None),
    1000: (('B1000', 1000, 1), ('B1000U', 32015, 32)),
    2000: (('B2000', 2000, 1), ('B2000', 2000, 1)),
    3000: (('B3000', 3000, 1), ('B3000', 3000, 1)),
    4000: (('B4000L', 15999, 4), ('B4000U', 16003, 4)),
    5000: (('B5000', 5000, 1), ('B5000', 5000, 1)),
    6000: (('B6000', 6000, 1), ('B6000', 6000, 1)),
    7000: (('B7000', 7000, 1), ('B7000', 7000, 1)),
    8000: (('B8000L', 31999, 4), ('B8000U', 64003, 8)),
    9000: (('B9000', 9000, 1), ('B9000', 9000, 1)),
    10000: (None, ('B10000U', 40001, 4)),
}
LP = int(mp.nint(log(pi) * 2**128))

A, B = int(sys.argv[1]), int(sys.argv[2])
Ln, Lnum, Lden = LEGS[A][0]
Un, Unum, Uden = LEGS[B][1]
L, U = Fr(Lnum, Lden), Fr(Unum, Uden)
T = f'{A}to{B}'
LOW = A == 0
RA = 3 if LOW else A
if LOW:
    assert L == 3
chal = open(f'challenge/Zeros{T}.lean').read()

# the zeros
allg = [l.split()[1] for l in open('data/zeros_T10000.txt') if not l.startswith('#')]
above = [l.split()[1] for l in open('data/zeros_above_10000.txt') if not l.startswith('#')]
gs = sorted(set(allg + above), key=mpf)
ords = [int(mp.nint(mpf(g) * 10**24)) for g in gs if A < mpf(g) <= B]
pre = [int(mp.nint(mpf(g) * 10**24)) for g in gs if mpf(L.numerator) / L.denominator < mpf(g) <= A]
post = [int(mp.nint(mpf(g) * 10**24)) for g in gs if B < mpf(g) <= mpf(U.numerator) / U.denominator]
assert pre == [], pre
body = chal[chal.index('def ord0'):chal.index('def ordinates')]
ms = [int(x) for x in re.findall(r'(\d{20,})', body)]
assert ms == ords, "challenge list differs from data"
n = len(ords) + len(post)


def nT(Tq):
    """(1 + 4 T²)/16 = nT / 2^eT for T = p/2^e"""
    p, q = Tq.numerator, Tq.denominator
    e = q.bit_length() - 1
    assert q == 2**e
    return q * q + 4 * p * p, 2 * e + 4


nL, eL = nT(L)
nU, eU = nT(U)
_, _, lL, kL, JL = entry(nL)
_, _, lU, kU, JU = entry(nU)

# numerics (not used by the proof): the window count
Lm, Um = mpf(L.numerator) / L.denominator, mpf(U.numerator) / U.denominator
Y = (Um / 2 * (mpf(lU) / 2**128 - eU * mpf(L2) / 2**160) - Lm / 2 * (mpf(lL) / 2**128 - eL * mpf(L2) / 2**160)
     - (Um - Lm) - (Um - Lm) * mpf(LP) / 2**128)
E = Um / 2 * (mpf(1) / 2**126 + mpf(eU) / 2**158) + Lm / 2 * (mpf(1) / 2**126 + mpf(eL) / 2**158) + (Um - Lm) / mpf(10)**20 + 1 / (4 * Lm)
c = 1 / Lm - 1 / Um


def argb(name):
    parts = open(f'ZetaCert/Legs/{name}/meta.txt').read().split()
    return float(parts[2]), float(parts[3])


a1lo, a1hi = argb(Ln)
a2lo, a2hi = argb(Un)
lo = (Y - E) / 2 - 6 * c + a2lo - a1hi - pi * (n - 1)
hi = pi * (n + 1) - ((Y + E) / 2 + 6 * c + a2hi - a1lo)
print(f"window ({float(Lm)}, {float(Um)}]: n = {n} ({len(ords)} + {len(post)} above b); "
      f"(Y/2)/π = {float(Y / 2 / pi):.4f}; margins {float(lo):.4f}, {float(hi):.4f} (must be > 0)")
assert lo > 0.01 and hi > 0.01

Lr = f"(({Lnum} : ℝ) / {Lden})"
Ur = f"(({Unum} : ℝ) / {Uden})"
hdr = "/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n"
with open(f'ZetaCert/Windows/W{T}.lean', 'w') as f:
    f.write(hdr)
    f.write(f"import ZetaCert.Legs.{Ln}\n")
    if Un != Ln:
        f.write(f"import ZetaCert.Legs.{Un}\n")
    f.write(f"""
/-! The count in the window `(L, U]`, `L = {Lnum}/{Lden}`, `U = {Unum}/{Uden}`: `Ncount L U = {n}`
(generated by scripts/gen_window.py). -/

namespace ZetaCert.Windows.W{T}

open ZetaCert ZetaCert.Window ZetaCert.Data Complex

theorem logL : |Real.log ({nL} : ℕ) - ({lL} : ℕ) / 2 ^ 128| ≤ 1 / 2 ^ 126 :=
  logCheck_spec log2_ok (k := {kL}) (J := {JL}) (by decide +kernel)

theorem logU : |Real.log ({nU} : ℕ) - ({lU} : ℕ) / 2 ^ 128| ≤ 1 / 2 ^ 126 :=
  logCheck_spec log2_ok (k := {kU}) (J := {JU}) (by decide +kernel)

theorem ncount : Zeta23.Ncount {Lr} {Ur} = {n} := by
  have hX := two_pi_dmu (L := {Lr}) (U := {Ur}) (nL := {nL}) (nU := {nU}) (eL := {eL}) (eU := {eU})
    (by norm_num) (by norm_num) (by norm_num) (by norm_num) logL logU
  refine ncount_window' (by norm_num) (by norm_num) Legs.{Ln}.leg Legs.{Un}.leg hX Legs.{Ln}.arg_bd
    Legs.{Un}.arg_bd ?_ ?_
  · have := Real.pi_gt_d20
    have := Real.pi_lt_d20
    norm_num [L2, LP]
    linarith
  · have := Real.pi_gt_d20
    have := Real.pi_lt_d20
    norm_num [L2, LP]
    linarith

end ZetaCert.Windows.W{T}
""")

# the solution
nmods = (n + 49) // 50
defs = chal[chal.index(f'namespace Zeros{T}'):chal.index('/-- Every zero')]
chunk_names = re.findall(r'def (ord\d+) : List', defs)
sizes = []
for cn in chunk_names:
    b0 = defs[defs.index(f'def {cn} '):]
    b0 = b0[:b0.index(']') + 1]
    sizes.append(len(re.findall(r'\d{20,}', b0)))
assert sum(sizes) == len(ords)
cL = math.ceil(L * 10**24)
cU = math.floor(U * 10**24)
if LOW:
    LOWLEMMA = """/-- No zero of `ζ` with `0 < Im s ≤ 3` (zeta-lab's `riemannZeta_ne_zero_of_im_le_three`, and
nontrivial zeros lie in the open strip). -/
theorem low {s : ℂ} (hz : riemannZeta s = 0) (h0 : 0 < s.im) (h3 : s.im ≤ 3) : False := by
  obtain ⟨r0, r1⟩ := ZetaCert.Assembly.re_strip hz h0
  exact RHHeight.riemannZeta_ne_zero_of_im_le_three r0 r1 h0 h3 hz

"""
    LOCATED = """  rintro s ⟨hz, ha, hb⟩
  by_cases h3 : s.im ≤ 3
  · exact (low hz ha h3).elim
  push Not at h3
  exact ZetaCert.Window.range_located whyp rhyp s hz (by exact_mod_cast h3) (by exact_mod_cast hb)
"""
    COUNT = f"""  have h := ZetaCert.Window.range_count whyp rhyp
  push_cast at h
  have e : zerosBetween 0 {B} = {{s : ℂ | riemannZeta s = 0 ∧ (3 : ℝ) < s.im ∧ s.im ≤ {B}}} := by
    ext s
    simp only [zerosBetween, Set.mem_setOf_eq]
    constructor
    · rintro ⟨hz, h0, h1⟩
      refine ⟨hz, ?_, h1⟩
      by_contra h
      push Not at h
      exact low hz h0 h
    · rintro ⟨hz, h3, h1⟩
      exact ⟨hz, by linarith, h1⟩
  rw [e, h, hlen]
"""
else:
    LOWLEMMA = ""
    LOCATED = """  rintro s ⟨hz, ha, hb⟩
  exact ZetaCert.Window.range_located whyp rhyp s hz (by exact_mod_cast ha) (by exact_mod_cast hb)
"""
    COUNT = """  have h := ZetaCert.Window.range_count whyp rhyp
  push_cast at h
  unfold zerosBetween
  rw [h, hlen]
"""
with open(f'solution/Zeros{T}Solution.lean', 'w') as f:
    f.write(hdr)
    f.write("import ZetaCert.Window\n")
    f.write(f"import ZetaCert.Windows.W{T}\n")
    if LOW:
        f.write("import RHHeight.LowHeight\n")
    for j in range(nmods):
        f.write(f"import ZetaCert.Zeros{T}.Z{j}\n")
    f.write(f"""
/-!
# Solution of `challenge/Zeros{T}.lean`

The definitions are copied verbatim from the challenge file. The window `(L, U]`,
`L = {Lnum}/{Lden}`, `U = {Unum}/{Uden}`, contains the {len(ords)} listed zeros and {len(post)} more above
{B} (`post`); `ZetaCert.Windows.W{T}.ncount` counts {n} zeros there, so `ZetaCert.Window.wmain`
shows that the certified zeros (`ZetaCert.Zeros{T}.Z*`) are all of them, and
`ZetaCert.Window.range_*` give the three statements. (Generated by scripts/gen_window.py.)
-/

open Complex ZetaCert.Zeros{T}

""")
    f.write(defs)
    f.write(f"/-- The certified zeros in the window above {B}. -/\ndef post : List ℕ := [{', '.join(map(str, post))}]\n\n")
    f.write("/-- The window list. -/\ndef ws : List ℕ := [] ++ ordinates ++ post\n\n")
    idx = 1
    for cn, sz in zip(chunk_names, sizes):
        zs = ", ".join(f"z_{i}" for i in range(idx, idx + sz))
        f.write(f"set_option maxRecDepth 100000 in\ntheorem hP_{cn} : ∀ m ∈ {cn}, ZetaCert.Assembly.P m :=\n"
                f"  List.forall_iff_forall_mem.mp (by unfold {cn}; exact ⟨{zs}⟩)\n\n")
        idx += sz
    if post:
        zs = ", ".join(f"z_{i}" for i in range(idx, idx + len(post)))
        if len(post) == 1:  # `List.Forall P [x]` reduces to `P x`, not to a conjunction
            zs = f"z_{idx}"
        f.write(f"theorem hP_post : ∀ m ∈ post, ZetaCert.Assembly.P m :=\n"
                f"  List.forall_iff_forall_mem.mp (by unfold post; exact {zs if len(post) == 1 else '⟨' + zs + '⟩'})\n\n")
    else:
        f.write("theorem hP_post : ∀ m ∈ post, ZetaCert.Assembly.P m := by simp [post]\n\n")
    cases = " | ".join(["hm"] * len(chunk_names))
    pat = "(" * (len(chunk_names) - 1) + "hm" + "".join(" | hm)" for _ in range(len(chunk_names) - 1))
    f.write(f"""theorem hP : ∀ m ∈ ws, ZetaCert.Assembly.P m := by
  intro m hm
  simp only [ws, ordinates, List.nil_append, List.mem_append] at hm
  rcases hm with {pat} | hm
""")
    for cn in chunk_names:
        f.write(f"  · exact hP_{cn} m hm\n")
    f.write("  · exact hP_post m hm\n\n")
    f.write(f"""theorem hchain : ws.IsChain (fun a b => a + 30000 < b) := by decide +kernel

instance : Trans (fun a b : ℕ => a + 30000 < b) (fun a b : ℕ => a + 30000 < b)
    (fun a b : ℕ => a + 30000 < b) := ⟨fun h1 h2 => by omega⟩

theorem hsep : ZetaCert.Assembly.Sep ws := List.isChain_iff_pairwise.mp hchain

theorem hrange : ∀ m ∈ ws, {cL} + 10 ^ 5 < m ∧ m + 10 ^ 5 < {cU} := by
  have h : ws.all (fun m => decide ({cL} + 10 ^ 5 < m ∧ m + 10 ^ 5 < {cU})) = true := by
    decide +kernel
  intro m hm
  simpa using List.all_eq_true.mp h m hm

theorem hlen : ordinates.length = {len(ords)} := by decide +kernel

theorem hlenws : ws.length = {n} := by decide +kernel

theorem whyp : ZetaCert.Window.WHyp ws {Lr} {Ur} {cL} {cU} :=
  ⟨hP, hsep, hrange, by norm_num, by norm_num, by norm_num,
    by rw [hlenws, ZetaCert.Windows.W{T}.ncount]⟩

{LOWLEMMA}theorem rhyp : ZetaCert.Window.RHyp [] ordinates post {RA} {B} {Lr} {Ur} := by
  refine ⟨by norm_num, by norm_num, ?_, by simp, ?_⟩
  · have h : ordinates.all (fun m => decide ({RA} * 10 ^ 24 + 10 ^ 5 < m ∧ m + 10 ^ 5 < {B} * 10 ^ 24)) = true := by
      decide +kernel
    intro m hm
    simpa using List.all_eq_true.mp h m hm
  · have h : post.all (fun m => decide ({B} * 10 ^ 24 + 10 ^ 5 < m)) = true := by decide +kernel
    intro m hm
    simpa using List.all_eq_true.mp h m hm

/-- Every zero of `ζ` with `{A} < Im s ≤ {B}` is simple, lies on the critical line, and has its
ordinate within `10⁻²⁰` of `m / 10²⁴` for some `m` in the list. -/
theorem located :
    ∀ s ∈ zerosBetween {A} {B}, s.re = 1 / 2 ∧ analyticOrderAt riemannZeta s = 1 ∧
      ∃ m ∈ ordinates, |s.im - (m : ℝ) / 10 ^ 24| ≤ 1 / 10 ^ 20 := by
{LOCATED}
/-- For each listed `m`, exactly one zero of `ζ` has its ordinate within `10⁻²⁰` of `m / 10²⁴`. -/
theorem unique :
    ∀ m ∈ ordinates, ∃! s : ℂ, riemannZeta s = 0 ∧ |s.im - (m : ℝ) / 10 ^ 24| ≤ 1 / 10 ^ 20 :=
  ZetaCert.Window.range_unique whyp rhyp

/-- There are exactly {len(ords)} zeros of `ζ` with `{A} < Im s ≤ {B}`. -/
theorem count : (zerosBetween {A} {B}).ncard = {len(ords)} := by
{COUNT}
end Zeros{T}
""")
print("wrote", f'ZetaCert/Windows/W{T}.lean', f'solution/Zeros{T}Solution.lean', nmods, "certificate modules expected")

