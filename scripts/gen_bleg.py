"""Generate a boundary-leg module for the window counts: Re ζ(σ + iT) > 0 for σ ∈ [1/2, 2], plus
bounds on Re and Im of ζ(1/2 + iT) and on arg ζ(1/2 + iT).

Like scripts/gen_leg.py (sample centres σ_i = j_i/4096 certified by `lc` and `seg_of_lc`), with
Euler–Maclaurin parameters chosen for the leg (|E0| ≤ 1e-6 instead of 1e-23) and a final module
`ZetaCert/Legs/<name>.lean` with `leg`, `half` (from `lcI` at σ = 1/2) and `arg_bd`.
Candidate data only (mpmath); the kernel re-checks everything.
Usage: python3 scripts/gen_bleg.py <num> <den> <name> [m]   (T = num/den, den a power of 2; m = 0 or
omitted: the m minimising the |ζ''| bound M2)
"""
import sys, math, os
from fractions import Fraction as Fr
from mpmath import mp, mpf, mpc, zeta
sys.path.insert(0, 'scripts')
from zeroparams import E0f, E1f, PRIMES

mp.dps = 30
num, den, name = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
m = int(sys.argv[4]) if len(sys.argv) > 4 else 0
T2 = Fr(num, den)
assert (2**80) % den == 0
G = num * (2**80 // den)


def choose_leg(t):
    for N in PRIMES:
        if N < 5: continue
        for k in range(1, 61):
            if E0f(N, k, t) <= mpf('1e-6') and E1f(N, k, t) <= mpf('1e-4'):
                return N, k
    raise ValueError("no parameters")


N, k = choose_leg(mpf(num) / den)
K = max(0, math.ceil(math.log2(8 * float(T2) * math.log(N)))) + 1
Dp = N.bit_length()
T = T2


def M2f(m):
    return 2 * (Fr(m)**4 + Fr(m)**3 / (T - 2) + Fr(1, 2 * m) + (1 + 4 * (T + Fr(1, 4))) / m) / Fr(3, 16)**2


if m == 0:
    m = min(range(1, 30), key=M2f)
M2 = M2f(m)


def vd(j):
    s = mpc(mpf(j) / 4096, mpf(num) / den)
    z = zeta(s); zp = zeta(s, derivative=1)
    v = Fr(math.floor((float(z.real) - 0.002) * 10**6), 10**6)
    d = Fr(math.ceil((abs(float(zp.real)) + abs(float(zp.imag)) + 0.002) * 10**6), 10**6)
    return v, d, z


def maxH(v, d):
    H = 256  # h ≤ 1/16
    while H > 0:
        h = Fr(H, 4096)
        if h * d + h * h * M2 < v * Fr(9, 10):
            return H
        H -= 1
    raise ValueError("no width")


pts = []
j = 2048
v, d, z0 = vd(j); H = maxH(v, d)
v0, d0 = v, d
pts.append((j, H, v, d))
while j + H < 8192:
    jn = min(8192, j + 2 * H)
    while True:
        vn, dn, _ = vd(jn); Hn = maxH(vn, dn)
        if jn - Hn <= j + H: break
        jn = (jn + j) // 2 + 1
    j, H, v, d = jn, Hn, vn, dn
    pts.append((j, H, v, d))
print(len(pts), "points; N", N, "k", k, "K", K, "M2", float(M2))

# bounds on Im ζ(1/2 + iT)
y = float(z0.imag)
wlo = Fr(math.floor((y - 0.002) * 10**6), 10**6)
whi = Fr(math.ceil((y + 0.002) * 10**6), 10**6)
assert wlo > 0 or whi < 0, ("Im too close to 0", y)


def q(x):
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"


def qR(x):
    return f"(({x.numerator} : ℝ) / {x.denominator})"


outdir = f'ZetaCert/Legs/{name}'
os.makedirs(outdir, exist_ok=True)
per = 40
chunks = [pts[i:i + per] for i in range(0, len(pts), per)]
P = f"fun σ : ℝ => 0 < (riemannZeta (σ + (({G} : ℕ) / 2 ^ 80 : ℝ) * I)).re"
for ci, ch in enumerate(chunks):
    with open(f'{outdir}/L{ci}.lean', 'w') as f:
        f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
        f.write("import ZetaCert.Leg\n\n")
        f.write(f"/-! Leg at height {num}/{den}, points {ci*per}–{ci*per+len(ch)-1} (generated by scripts/gen_bleg.py). -/\n\n")
        f.write(f"namespace ZetaCert.Legs.{name}\n\nopen ZetaCert Complex Set\n\n")
        for i, (j, H, v, d) in enumerate(ch):
            f.write(f"theorem p_{ci}_{i} : ∀ σ ∈ Icc (({j} : ℕ) / 4096 - ({H} : ℝ) / 4096) (({j} : ℕ) / 4096 + ({H} : ℝ) / 4096),\n"
                    f"    ({P}) σ :=\n"
                    f"  seg_of_lc (j := {j}) (G := {G}) (N := {N}) (K := {K}) (k := {k}) (fuel := 1000) (Dp := {Dp}) (m := {m})\n"
                    f"    (v := {q(v)}) (d := {q(d)}) (h := ({H} : ℝ) / 4096)\n"
                    f"    (by decide +kernel) (by norm_num) (by norm_num) (by norm_num) (by positivity) (by norm_num)\n"
                    f"    (by unfold M2; norm_num)\n\n")
        chain = f"p_{ci}_0"
        for i in range(1, len(ch)):
            chain = f"cover2 ({chain}) p_{ci}_{i} (by norm_num)"
        j0, H0 = ch[0][0], ch[0][1]; j1, H1 = ch[-1][0], ch[-1][1]
        f.write(f"theorem part_{ci} : ∀ σ ∈ Icc (({j0} : ℕ) / 4096 - ({H0} : ℝ) / 4096) (({j1} : ℕ) / 4096 + ({H1} : ℝ) / 4096),\n"
                f"    ({P}) σ :=\n  {chain}\n\nend ZetaCert.Legs.{name}\n")

Tl = f"((({num} : ℝ) / {den} : ℝ) : ℂ)"
with open(f'ZetaCert/Legs/{name}.lean', 'w') as f:
    f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
    f.write("import ZetaCert.Window\n")
    for ci in range(len(chunks)):
        f.write(f"import ZetaCert.Legs.{name}.L{ci}\n")
    f.write(f"\n/-! The leg at `T = {num}/{den}` (generated by scripts/gen_bleg.py): `Re ζ(σ + iT) > 0` on\n"
            f"`[1/2, 2]`, and bounds on `ζ(1/2 + iT)` and its argument. -/\n\n"
            f"namespace ZetaCert.Legs.{name}\n\nopen ZetaCert ZetaCert.Window Complex Set\n\n")
    chain = "part_0"
    for ci in range(1, len(chunks)):
        chain = f"cover2 ({chain}) part_{ci} (by norm_num)"
    j0, H0 = chunks[0][0][0], chunks[0][0][1]; j1, H1 = chunks[-1][-1][0], chunks[-1][-1][1]
    f.write(f"theorem leg_all : ∀ σ ∈ Icc (({j0} : ℕ) / 4096 - ({H0} : ℝ) / 4096) (({j1} : ℕ) / 4096 + ({H1} : ℝ) / 4096),\n"
            f"    ({P}) σ :=\n  {chain}\n\n")
    f.write(f"theorem eT : ((({G} : ℕ) : ℝ) / 2 ^ 80 : ℝ) = ({num} : ℝ) / {den} := by norm_num\n\n")
    f.write(f"theorem leg : ∀ σ ∈ Icc (1 / 2 : ℝ) 2, 0 < (riemannZeta (σ + {Tl} * I)).re := by\n"
            f"  intro σ hσ\n"
            f"  have h := leg_all σ ⟨by norm_num at hσ ⊢; linarith [hσ.1], by norm_num at hσ ⊢; linarith [hσ.2]⟩\n"
            f"  simp only at h; rw [eT] at h; exact h\n\n")
    f.write(f"theorem half : {qR(v0)} ≤ (riemannZeta (1 / 2 + {Tl} * I)).re ∧\n"
            f"    {qR(wlo)} ≤ (riemannZeta (1 / 2 + {Tl} * I)).im ∧\n"
            f"    (riemannZeta (1 / 2 + {Tl} * I)).im ≤ {qR(whi)} := by\n"
            f"  have h := half_point (G := {G}) (N := {N}) (K := {K}) (k := {k}) (fuel := 1000) (Dp := {Dp})\n"
            f"    (v := {q(v0)}) (d := {q(d0)}) (wlo := {q(wlo)}) (whi := {q(whi)}) (by decide +kernel)\n"
            f"  rw [eT] at h\n"
            f"  obtain ⟨h1, h2, h3⟩ := h\n"
            f"  refine ⟨le_of_eq_of_le ?_ h1, le_of_eq_of_le ?_ h2, h3.trans (le_of_eq ?_)⟩ <;> norm_num\n\n")
    # arg bounds
    vv = float(v0)
    if wlo > 0:
        bq = whi / v0
        if float(bq) < math.pi / 2:
            lo, hi = "0", f"{qR(whi)} / {qR(v0)}"
            pf = (f"  exact arg_bounds_of_im_nonneg (by norm_num) h1 (by linarith) h3")
            arg = (0.0, float(bq))
        else:
            lo, hi = "0", "Real.pi / 2"
            pf = (f"  exact ⟨(arg_bounds_of_im_nonneg (by norm_num) h1 (by linarith) h3).1,\n"
                  f"    (abs_lt.mp ((Complex.abs_arg_lt_pi_div_two_iff).mpr (Or.inl (by linarith)))).2.le⟩")
            arg = (0.0, math.pi / 2)
    else:
        bq = wlo / v0
        if float(bq) > -math.pi / 2:
            lo, hi = f"{qR(wlo)} / {qR(v0)}", "0"
            pf = (f"  exact arg_bounds_of_im_neg (by norm_num) h1 (by linarith) h2")
            arg = (float(bq), 0.0)
        else:
            lo, hi = "-(Real.pi / 2)", "0"
            pf = (f"  exact ⟨(abs_lt.mp ((Complex.abs_arg_lt_pi_div_two_iff).mpr (Or.inl (by linarith)))).1.le,\n"
                  f"    (arg_bounds_of_im_neg (by norm_num) h1 (by linarith) h2).2⟩")
            arg = (-math.pi / 2, 0.0)
    f.write(f"/-- Bounds on `arg ζ(1/2 + iT)`; numerically (not used) the argument is {math.atan2(float(z0.imag), float(z0.real)):.4f}. -/\n"
            f"theorem arg_bd : {lo} ≤ (riemannZeta (1 / 2 + {Tl} * I)).arg ∧\n"
            f"    (riemannZeta (1 / 2 + {Tl} * I)).arg ≤ {hi} := by\n"
            f"  obtain ⟨h1, h2, h3⟩ := half\n{pf}\n\n")
    f.write(f"end ZetaCert.Legs.{name}\n")
# summary for the window generator
with open(f'{outdir}/meta.txt', 'w') as f:
    f.write(f"{num} {den} {arg[0]!r} {arg[1]!r} {lo}|{hi}\n")
print("arg bounds", arg, "true", math.atan2(float(z0.imag), float(z0.real)))
