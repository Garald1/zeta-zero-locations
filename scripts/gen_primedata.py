"""Generate prime data for the kernel evaluator: (p, w, L) with w = floor(2^128/sqrt p),
L = round(2^128 log p), and the log-certificate parameters (k, J). Candidate data only:
every property is re-checked by the kernel (wOK, logCheck)."""
import sys, math
from mpmath import mp, log, mpf
mp.dps = 120

def primes_upto(N):
    s = bytearray([1]) * (N + 1); s[0] = s[1] = 0
    for i in range(2, int(N**0.5) + 1):
        if s[i]: s[i*i::i] = bytearray(len(s[i*i::i]))
    return [i for i in range(N + 1) if s[i]]

def entry(p):
    w = math.isqrt(2**256 // p)
    while (w + 1)**2 * p <= 2**256: w += 1
    while w * w * p > 2**256: w -= 1
    L = int(mp.nint(log(p) * 2**128))
    k = p.bit_length() - 1
    a, b = p - 2**k, p + 2**k
    J = 1
    x = mpf(a) / b
    while x > 0 and 2 * x**(2*J+1) / ((2*J+1) * (1 - x*x)) > mpf(2)**-131: J += 1
    return p, w, L, k, J

L2 = int(mp.nint(log(2) * 2**160))

if __name__ == "__main__":
    PMAX = int(sys.argv[1]); out = sys.argv[2]
    ps = primes_upto(PMAX)
    ents = [entry(p) for p in ps]
    with open(out, "w") as f:
        f.write("/-\nCopyright (c) 2026 Harald Helfgott. All rights reserved.\nReleased under Apache 2.0 license.\n-/\n")
        f.write(f"/-! Prime data up to {PMAX}, generated by scripts/gen_primedata.py (candidate data;\nchecked by the kernel in ZetaCert/PrimeDataCheck*.lean). -/\n\nnamespace ZetaCert.Data\n\n")
        f.write(f"/-- `round(2^160 log 2)`. -/\ndef L2 : Nat := {L2}\n\n")
        chunks = [ents[i:i+150] for i in range(0, len(ents), 150)]
        for ci, ch in enumerate(chunks):
            f.write(f"/-- `(p, w, L, k, J)`, chunk {ci}. -/\ndef pc{ci} : List (Nat × Nat × Nat × Nat × Nat) := [\n")
            f.write(",\n".join(f"  ({p}, {w}, {L}, {k}, {J})" for p, w, L, k, J in ch))
            f.write("]\n\n")
        f.write("/-- All chunks. -/\ndef pcAll : List (Nat × Nat × Nat × Nat × Nat) := " + " ++ ".join(f"pc{i}" for i in range(len(chunks))) + "\n\n")
        f.write(f"/-- Number of chunks. -/\ndef nChunks : Nat := {len(chunks)}\n\nend ZetaCert.Data\n")
    print(len(ps), "primes,", len(chunks), "chunks; max J", max(e[4] for e in ents))
    # Palomar requires the module system for every .lean file: see scripts/port_module.py.
    sys.path.insert(0, 'scripts')
    from port_module import port_files
    port_files([out])
